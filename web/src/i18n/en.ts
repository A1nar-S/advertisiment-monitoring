// Forms by Intl.PluralRules category: English uses one and other; Latvian
// also zero (0, 10–20, 30, ...: "10 sludinājumu").
export type Plural = { zero?: string; one: string; other: string }
export const plural = (one: string, other: string, zero?: string): Plural =>
  zero === undefined ? { one, other } : { zero, one, other }

